#!/usr/bin/env node
/**
 * Brand asset guard.
 *
 * Two defects have shipped in launcher icons before and both are invisible in
 * a file listing:
 *
 *  1. A second shade of blue baked into the artwork (a blue disc inside the
 *     Android adaptive foreground) shows up as a faded ring over the adaptive
 *     background colour.
 *  2. Artwork sized by its bounding box instead of its radial extent. The
 *     speech-bubble tail sticks out diagonally, so a mark that "fits" the
 *     square still gets a notch cut out of it by a circular launcher mask.
 *
 * This check re-derives both properties straight from the pixels, so an
 * icon regenerated by hand cannot quietly reintroduce either one.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

/** The single flat brand blue. Every logo surface uses exactly this colour. */
const BRAND = { r: 15, g: 169, b: 255 };
const COLOUR_TOLERANCE = 14;
/** Alpha above which a pixel counts as fully painted rather than an edge. */
const OPAQUE = 250;
/** Pixels at least this white belong to the mark, not the background. */
const MARK_WHITENESS = 0.6;
/**
 * Android composites an adaptive icon on a 108dp canvas but only guarantees
 * the centre 66dp circle survives every launcher mask.
 */
const ADAPTIVE_SAFE_RADIUS = 66 / 108 / 2;

// 'flat' = full-bleed brand blue (no transparent corner can read as white),
// 'shaped' = blue disc on transparency, 'transparent' = bare white artwork.
const ASSETS = [
  {
    file: 'artifacts/mobile/assets/images/avarpus-icon-universal-square.png',
    size: 1024,
    background: 'flat',
    // A launcher may circle-mask a plain icon, so stay inside the inscribed
    // circle. The tail is allowed to reach that edge, never to cross it.
    maxMarkRadius: 0.49,
  },
  {
    file: 'artifacts/mobile/assets/images/avarpus-icon-legacy.png',
    size: 512,
    background: 'flat',
    maxMarkRadius: 0.49,
  },
  {
    file: 'artifacts/mobile/assets/images/avarpus-adaptive-foreground.png',
    size: 1024,
    background: 'transparent',
    maxMarkRadius: ADAPTIVE_SAFE_RADIUS,
  },
  {
    file: 'artifacts/mobile/assets/images/avarpus-logo-circle.png',
    size: 1024,
    background: 'shaped',
    maxMarkRadius: 0.47,
  },
  {
    file: 'artifacts/mobile/assets/images/avarpus-primary-logo.png',
    size: 1254,
    background: 'shaped',
    maxMarkRadius: 0.47,
  },
  {
    file: 'artifacts/mobile/assets/images/avarpus-splash-mark.png',
    size: 1254,
    background: 'transparent',
    maxMarkRadius: 0.5,
  },
  {
    file: 'artifacts/avarpus-official-site/public/favicon.png',
    size: 512,
    background: 'flat',
    maxMarkRadius: 0.49,
  },
  {
    file: 'artifacts/avarpus-official-site/public/avarpus-logo.png',
    size: 1024,
    background: 'shaped',
    maxMarkRadius: 0.47,
  },
  {
    file: 'artifacts/avarpus-web/public/favicon.png',
    size: 512,
    background: 'flat',
    maxMarkRadius: 0.49,
  },
  {
    file: 'artifacts/update-admin/public/avarpus-favicon.png',
    size: 128,
    background: 'flat',
    maxMarkRadius: 0.49,
  },
  {
    file: 'artifacts/update-admin/public/avarpus-favicon-dark.png',
    size: 128,
    background: 'flat',
    maxMarkRadius: 0.49,
  },
];

const failures = [];

function fail(file, message) {
  failures.push(`${file}: ${message}`);
}

function readPixels(absPath) {
  const [width, height] = execFileSync('identify', ['-format', '%w %h', absPath], {
    encoding: 'utf8',
  })
    .trim()
    .split(' ')
    .map(Number);
  const data = execFileSync('magick', [absPath, '-depth', '8', 'RGBA:-'], {
    maxBuffer: 1024 * 1024 * 256,
  });
  if (data.length !== width * height * 4) {
    throw new Error(`unexpected raw buffer for ${absPath}`);
  }
  return { width, height, data };
}

function checkAsset(spec) {
  const absPath = path.join(ROOT, spec.file);
  let image;
  try {
    image = readPixels(absPath);
  } catch (error) {
    fail(spec.file, `could not be read (${error.message})`);
    return;
  }

  const { width, height, data } = image;
  if (width !== spec.size || height !== spec.size) {
    fail(spec.file, `expected ${spec.size}x${spec.size}, found ${width}x${height}`);
    return;
  }

  const centre = spec.size / 2;
  const limit = spec.maxMarkRadius * spec.size;
  let worstRadius = 0;
  let offPalette = 0;
  let opaqueCorners = 0;
  let brandCorners = 0;

  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      const i = (y * width + x) * 4;
      const [r, g, b, a] = [data[i], data[i + 1], data[i + 2], data[i + 3]];
      if (a < OPAQUE) continue;

      // Every painted pixel must sit on the white -> brand ramp. Anything else
      // is a second shade, a gradient, or a stray colour.
      const t = (r - BRAND.r) / (255 - BRAND.r);
      const expectedG = BRAND.g + t * (255 - BRAND.g);
      const onRamp =
        t >= -0.05 &&
        t <= 1.05 &&
        Math.abs(g - expectedG) <= COLOUR_TOLERANCE &&
        Math.abs(b - 255) <= COLOUR_TOLERANCE;
      if (!onRamp) offPalette += 1;

      if (t >= MARK_WHITENESS) {
        const radius = Math.hypot(x + 0.5 - centre, y + 0.5 - centre);
        if (radius > worstRadius) worstRadius = radius;
      }
    }
  }

  for (const [x, y] of [
    [0, 0],
    [width - 1, 0],
    [0, height - 1],
    [width - 1, height - 1],
  ]) {
    const i = (y * width + x) * 4;
    if (data[i + 3] >= OPAQUE) {
      opaqueCorners += 1;
      const matches =
        Math.abs(data[i] - BRAND.r) <= COLOUR_TOLERANCE &&
        Math.abs(data[i + 1] - BRAND.g) <= COLOUR_TOLERANCE &&
        Math.abs(data[i + 2] - BRAND.b) <= COLOUR_TOLERANCE;
      if (matches) brandCorners += 1;
    }
  }

  if (offPalette > 0) {
    fail(
      spec.file,
      `${offPalette} pixel(s) are neither the brand blue nor white - the logo area must be one flat colour`,
    );
  }
  if (worstRadius > limit) {
    fail(
      spec.file,
      `mark reaches ${worstRadius.toFixed(0)}px from centre but must stay within ${limit.toFixed(0)}px, so a mask would clip it`,
    );
  }
  if (spec.background === 'flat' && brandCorners !== 4) {
    fail(spec.file, 'full-bleed icon must be opaque brand blue in all four corners');
  }
  if (spec.background === 'transparent' && opaqueCorners !== 0) {
    fail(
      spec.file,
      'must be artwork on transparency - a baked-in background disc shows as a ring',
    );
  }
  if (spec.background === 'shaped' && opaqueCorners !== 0) {
    fail(spec.file, 'rounded tile must have transparent corners');
  }
}

for (const spec of ASSETS) {
  checkAsset(spec);
}

// The adaptive background colour must be the same flat blue as the artwork,
// otherwise the foreground reads as a disc floating on a different shade.
const appJsonPath = path.join(ROOT, 'artifacts/mobile/app.json');
const appJson = JSON.parse(readFileSync(appJsonPath, 'utf8'));
const brandHex = `#${[BRAND.r, BRAND.g, BRAND.b]
  .map((v) => v.toString(16).padStart(2, '0'))
  .join('')}`.toUpperCase();
const adaptiveBackground = appJson?.expo?.android?.adaptiveIcon?.backgroundColor;
if (String(adaptiveBackground).toUpperCase() !== brandHex) {
  fail(
    'artifacts/mobile/app.json',
    `android.adaptiveIcon.backgroundColor is ${adaptiveBackground}, expected ${brandHex}`,
  );
}

if (failures.length > 0) {
  console.error('Brand asset validation failed:');
  for (const failure of failures) console.error(`  - ${failure}`);
  process.exit(1);
}

console.log(`Brand asset validation passed (${ASSETS.length} icons, flat ${brandHex}).`);
